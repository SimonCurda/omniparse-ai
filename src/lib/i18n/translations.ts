/**
 * Look up a translation key. Supports two placeholder patterns:
 *   {name}        — substituted with params.name
 *   {strong}...{/strong}  — extracted and re-inserted as raw string (the
 *                  caller is responsible for rendering it as <strong>).
 *                  The closing {/strong} marker is stripped from the
 *                  output; the caller splits on {strong} to wrap content.
 *
 * Falls back to English if the key is missing in the requested language.
 * Falls back to the key itself if missing from both (so missing keys are
 * obvious in the UI).
 */
export function translate(lang: Language, key: string, params?: Record<string, string | number>): string {
  let str = translations[lang]?.[key] ?? translations.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return str;
}

/**
 * Detect the user's preferred language from the browser.
 * Used on first load (before the user has toggled anything).
 * Falls back to 'en' for any unsupported locale.
 */
export function detectBrowserLanguage(): Language {
  if (typeof navigator === 'undefined') return DEFAULT_LANGUAGE;
  const langs = navigator.languages ?? [navigator.language];
  for (const l of langs) {
    const lower = l.toLowerCase();
    if (lower.startsWith('cs') || lower.startsWith('cz')) return 'cz';
    if (lower.startsWith('sk')) return 'sk';
    if (lower.startsWith('de')) return 'de';
  }
  return DEFAULT_LANGUAGE;
}
